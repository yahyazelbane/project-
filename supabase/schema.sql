-- CampusFlow: schema et règles d'accès
-- Exécutez ce script dans Supabase > SQL Editor.
create table if not exists public.students (
  id bigint generated by default as identity primary key,
  nom text not null,
  prenom text not null,
  email text,
  filiere text not null,
  niveau text not null default '1ère année',
  created_at timestamptz not null default now()
);

alter table public.students enable row level security;

-- Seuls les utilisateurs connectés peuvent lire et gérer les étudiants.
-- Créez uniquement des comptes de confiance dans Supabase Authentication.
drop policy if exists "Authenticated users can read students" on public.students;
create policy "Authenticated users can read students"
on public.students for select to authenticated using (true);

drop policy if exists "Authenticated users can insert students" on public.students;
create policy "Authenticated users can insert students"
on public.students for insert to authenticated with check (true);

drop policy if exists "Authenticated users can update students" on public.students;
create policy "Authenticated users can update students"
on public.students for update to authenticated using (true) with check (true);

drop policy if exists "Authenticated users can delete students" on public.students;
create policy "Authenticated users can delete students"
on public.students for delete to authenticated using (true);
